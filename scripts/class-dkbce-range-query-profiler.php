<?php
/**
 * Profile generated range queries with WP-CLI; never loaded by the plugin.
 *
 * Usage: wp eval-file scripts/class-dkbce-range-query-profiler.php '{"page":10,"samples":5}'
 * Optional "filters" replaces the default scenario matrix with validated plugin filters.
 *
 * @package BulkCOGSEditor
 */

if ( ! defined( 'WP_CLI' ) || ! WP_CLI ) {
	exit;
}

/**
 * Capture real WooCommerce SQL and compare offset and existing cursor access.
 */
class DKBCE_Range_Query_Profiler {
	/**
	 * Product matching service.
	 *
	 * @var DKBCE_COGS_Service
	 */
	private $service;

	/**
	 * Last generated product query.
	 *
	 * @var string
	 */
	private $sql = '';

	/**
	 * Whether the captured query should also calculate the total.
	 *
	 * @var bool
	 */
	private $counting = false;

	/**
	 * Set up profiling without registering permanent callbacks.
	 */
	public function __construct() {
		$this->service = new DKBCE_COGS_Service();
	}

	/**
	 * Disable result caching only while capturing this profiler's product query.
	 *
	 * @param array $query Query arguments.
	 * @return array
	 */
	public function configure_query( $query ) {
		$query['cache_results']       = false;
		$query['no_found_rows']       = ! $this->counting;
		$query['dkbce_profile_query'] = true;
		return $query;
	}

	/**
	 * Record the generated SELECT without rewriting its predicates.
	 *
	 * @param string   $sql Generated SQL.
	 * @param WP_Query $query Query object.
	 * @return string
	 */
	public function capture_sql( $sql, $query ) {
		if ( $query->get( 'dkbce_profile_query' ) ) {
			$this->sql = $sql;
		}
		return $sql;
	}

	/**
	 * Generate one real query with temporary capture hooks.
	 *
	 * @param array $filters Normalized plugin filters.
	 * @param bool  $counting Include the count used by ordinary previews.
	 * @return string
	 * @throws RuntimeException When the CPT query cannot be captured.
	 */
	private function capture( $filters, $counting ) {
		$this->sql      = '';
		$this->counting = $counting;
		add_filter( 'woocommerce_product_data_store_cpt_get_products_query', array( $this, 'configure_query' ), PHP_INT_MAX );
		add_filter( 'posts_request', array( $this, 'capture_sql' ), PHP_INT_MAX, 2 );
		try {
			$this->service->scan_matches( $filters );
		} finally {
			remove_filter( 'posts_request', array( $this, 'capture_sql' ), PHP_INT_MAX );
			remove_filter( 'woocommerce_product_data_store_cpt_get_products_query', array( $this, 'configure_query' ), PHP_INT_MAX );
		}
		if ( ! preg_match( '/^\s*SELECT\b/i', $this->sql ) ) {
			throw new RuntimeException( 'No product SELECT captured. Check that the CPT product data store is active.' );
		}
		return $this->sql;
	}

	/**
	 * Execute only captured SELECT statements, including the immediate total read.
	 *
	 * @param string $sql Captured SQL.
	 * @return array
	 * @throws RuntimeException When a diagnostic SELECT fails.
	 */
	private function execute( $sql ) {
		global $wpdb;
		$started = microtime( true );
		// phpcs:ignore WordPress.DB.DirectDatabaseQuery.DirectQuery, WordPress.DB.DirectDatabaseQuery.NoCaching, WordPress.DB.PreparedSQL.NotPrepared -- Diagnostic SELECT generated by WooCommerce, deliberately uncached.
		$ids = $wpdb->get_col( $sql );
		if ( $wpdb->last_error ) {
			throw new RuntimeException( esc_html( $wpdb->last_error ) );
		}
		$total = null;
		if ( false !== stripos( $sql, 'SQL_CALC_FOUND_ROWS' ) ) {
			// phpcs:ignore WordPress.DB.DirectDatabaseQuery.DirectQuery, WordPress.DB.DirectDatabaseQuery.NoCaching -- Read immediately after its matching SELECT.
			$total = (int) $wpdb->get_var( 'SELECT FOUND_ROWS()' );
			if ( $wpdb->last_error ) {
				throw new RuntimeException( esc_html( $wpdb->last_error ) );
			}
		}
		return array(
			'ids'     => array_map( 'intval', $ids ),
			'total'   => $total,
			'time_ms' => ( microtime( true ) - $started ) * 1000,
		);
	}

	/**
	 * Record EXPLAIN and repeated warm timings; no EXPLAIN ANALYZE or DDL.
	 *
	 * @param string $sql Captured SELECT.
	 * @param int    $samples Number of timed samples.
	 * @return array
	 * @throws RuntimeException When EXPLAIN fails.
	 */
	private function measure( $sql, $samples ) {
		global $wpdb;
		// phpcs:ignore WordPress.DB.DirectDatabaseQuery.DirectQuery, WordPress.DB.DirectDatabaseQuery.NoCaching, WordPress.DB.PreparedSQL.NotPrepared -- EXPLAIN of a captured WooCommerce SELECT, deliberately uncached.
		$plan = $wpdb->get_results( 'EXPLAIN ' . $sql, ARRAY_A );
		if ( $wpdb->last_error ) {
			throw new RuntimeException( esc_html( $wpdb->last_error ) );
		}
		$this->execute( $sql ); // Warm once, outside the reported samples.
		$times = array();
		for ( $sample = 0; $sample < $samples; ++$sample ) {
			$result  = $this->execute( $sql );
			$times[] = $result['time_ms'];
		}
		sort( $times );
		$middle = (int) floor( $samples / 2 );
		return array(
			'sql'        => $sql,
			'explain'    => $plan,
			'ids'        => $result['ids'],
			'total'      => $result['total'],
			'median_ms'  => 0 === $samples % 2 ? ( $times[ $middle - 1 ] + $times[ $middle ] ) / 2 : $times[ $middle ],
			'p95_ms'     => $times[ (int) ceil( $samples * 0.95 ) - 1 ],
			'samples_ms' => $times,
		);
	}

	/**
	 * Profile broad, selective, combined, and six-decimal range predicates.
	 *
	 * @param array $config Optional filters, requested page, page size and samples.
	 * @return array
	 * @throws InvalidArgumentException When filters or page size are invalid.
	 */
	public function run( $config ) {
		global $wpdb;
		$samples   = max( 1, min( 20, absint( $config['samples'] ?? 5 ) ) );
		$page      = max( 1, min( 100000, absint( $config['page'] ?? 10 ) ) );
		$page_size = absint( $config['page_size'] ?? 20 );
		if ( ! in_array( $page_size, DKBCE_COGS_Service::PREVIEW_PAGE_SIZES, true ) ) {
			throw new InvalidArgumentException( 'Use a supported preview page size: 10, 20, 50 or 100.' );
		}
		$scenarios = array(
			'all'          => array(),
			'price_broad'  => array(
				'price_min' => '0',
				'price_max' => DKBCE_COGS_Service::MAX_AMOUNT,
			),
			'price_narrow' => array(
				'price_min' => '100',
				'price_max' => '150',
			),
			'cogs_narrow'  => array(
				'cogs_min' => '10',
				'cogs_max' => '20',
			),
			'combined'     => array(
				'price_min' => '100',
				'price_max' => '150',
				'cogs_min'  => '0',
				'cogs_max'  => DKBCE_COGS_Service::MAX_AMOUNT,
			),
			'price_exact'  => array(
				'price_min' => '100',
				'price_max' => '100',
			),
		);
		if ( wc_get_price_decimals() >= 6 ) {
			$scenarios['six_decimals'] = array(
				'cogs_min' => '10.000001',
				'cogs_max' => '10.000009',
			);
		}
		$categories = get_terms(
			array(
				'taxonomy'   => 'product_cat',
				'hide_empty' => true,
				'number'     => 1,
				'orderby'    => 'term_id',
			)
		);
		if ( ! is_wp_error( $categories ) && $categories ) {
			$scenarios['category']          = array( 'category' => array( $categories[0]->term_id ) );
			$scenarios['combined_category'] = $scenarios['combined'] + $scenarios['category'];
		}
		if ( isset( $config['filters'] ) ) {
			$scenarios = array( 'custom' => $config['filters'] );
		}
		$report = array(
			'captured_at_utc'  => gmdate( 'c' ),
			'wordpress'        => get_bloginfo( 'version' ),
			'woocommerce'      => WC_VERSION,
			'php'              => PHP_VERSION,
			'filter_decimals'  => wc_get_price_decimals(),
			'persistent_cache' => (bool) wp_using_ext_object_cache(),
			'samples'          => $samples,
			'requested_page'   => $page,
			'page_size'        => $page_size,
		);
		// phpcs:ignore WordPress.DB.DirectDatabaseQuery.DirectQuery, WordPress.DB.DirectDatabaseQuery.NoCaching -- Read-only environment metadata for the profile.
		$report['database'] = $wpdb->get_var( 'SELECT VERSION()' );
		// phpcs:ignore WordPress.DB.DirectDatabaseQuery.DirectQuery, WordPress.DB.DirectDatabaseQuery.NoCaching -- Catalog cardinalities for interpreting the profile.
		$report['post_counts'] = $wpdb->get_results( $wpdb->prepare( 'SELECT post_type, post_status, COUNT(*) AS total FROM %i WHERE post_type IN (%s, %s) GROUP BY post_type, post_status', $wpdb->posts, 'product', 'product_variation' ), ARRAY_A );
		foreach ( array( $wpdb->posts, $wpdb->postmeta, $wpdb->term_relationships, $wpdb->term_taxonomy, $wpdb->wc_product_meta_lookup ) as $table ) {
			// phpcs:ignore WordPress.DB.DirectDatabaseQuery.DirectQuery, WordPress.DB.DirectDatabaseQuery.NoCaching -- Inspect installed indexes without altering them.
			$report['indexes'][ $table ] = $wpdb->get_results( $wpdb->prepare( 'SHOW INDEX FROM %i', $table ), ARRAY_A );
		}
		// phpcs:ignore WordPress.DB.DirectDatabaseQuery.DirectQuery, WordPress.DB.DirectDatabaseQuery.NoCaching -- Detect installed lookup precision and optional COGS support.
		$report['lookup_columns'] = $wpdb->get_results( $wpdb->prepare( 'SHOW COLUMNS FROM %i', $wpdb->wc_product_meta_lookup ), ARRAY_A );
		foreach ( $scenarios as $name => $raw ) {
			$filters = $this->service->validate_filters( $raw );
			if ( is_wp_error( $filters ) ) {
				throw new InvalidArgumentException( esc_html( $filters->get_error_message() ) );
			}
			$count        = $this->measure( $this->capture( $filters + array( 'count' => true ), true ), $samples );
			$target_page  = min( $page, max( 1, (int) ceil( $count['total'] / $page_size ) ) );
			$page_filters = $filters + array(
				'get_ids'   => true,
				'page_size' => $page_size,
				'page_no'   => $target_page,
			);
			$preview      = $this->measure( $this->capture( $page_filters, true ), $samples );
			$offset       = $this->measure( $this->capture( $page_filters, false ), $samples );
			$boundary     = null;
			$after_id     = 0;
			if ( $target_page > 1 ) {
				$previous            = $page_filters;
				$previous['page_no'] = $target_page - 1;
				$boundary            = $this->measure( $this->capture( $previous, false ), $samples );
				$after_id            = (int) end( $boundary['ids'] );
			}
			$cursor                       = $this->measure( $this->capture( $page_filters + array( 'after_id' => $after_id ), false ), $samples );
			$report['scenarios'][ $name ] = array(
				'filters'           => $filters,
				'page'              => $target_page,
				'after_id'          => $after_id,
				'ordered_ids_match' => $offset['ids'] === $cursor['ids'] && $offset['ids'] === $preview['ids'],
				'count'             => $count,
				'preview'           => $preview,
				'offset'            => $offset,
				'boundary'          => $boundary,
				'cursor'            => $cursor,
			);
		}
		return $report;
	}
}

try {
	$dkbce_profile_config = isset( $args[0] ) ? json_decode( $args[0], true ) : array();
	if ( ! is_array( $dkbce_profile_config ) ) {
		throw new InvalidArgumentException( 'Pass a JSON object as the optional configuration argument.' );
	}
	WP_CLI::line( wp_json_encode( ( new DKBCE_Range_Query_Profiler() )->run( $dkbce_profile_config ), JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES ) );
} catch ( Throwable $dkbce_profile_error ) {
	WP_CLI::error( $dkbce_profile_error->getMessage() );
}
